/** 場面の台本を作る。kind：talk / date / confess / propose / home */
export function script(kind, id, ctx) {
  const c = CHAR[id], S = STORY[id], R = Math.random;
  const pick = a => a[Math.floor(R() * a.length)];
  const pref = PREF[id] || 'gentle';
  if (!S) return [{ who: id, text: '……' }];
  if (kind === 'talk') {
    const out = [];
    if (ctx.bond >= 55 && S.deep) out.push({ who: id, text: pick(S.deep) });
    else out.push({ who: id, text: pick(S.talk) });
    out.push({ choice: ['「話してくれて、ありがとう」', '「もっと君のことを知りたい」'], res: [
      { who: id, text: pref === 'gentle' ? '……そう言ってもらえて、嬉しい。' : '……ふふ、ずいぶん積極的ね。' },
      { who: id, text: pref === 'bold' ? '望むところよ。何でも聞いて。' : '……そんなふうに言われると、照れてしまう。' }], good: pref === 'gentle' ? 0 : 1 });
    return out;
  }
  if (kind === 'date') {
    const P = ctx.place;
    return [{ who: null, text: P.lead }, { who: null, text: P.q },
      { choice: [P.a[0], P.b[0]], res: [{ who: null, text: P.a[1] }, { who: null, text: P.b[1] }], good: pref === 'gentle' ? 0 : 1 },
      { who: id, text: ctx.bond >= 55 ? pick(S.deep) : pick(S.talk) }]  ;
  }
  if (kind === 'confess') return [{ who: null, text: c.name + 'の前に立つ。胸が高鳴る。「……ずっと、あなたのことを想っていた」' }, { who: id, text: S.confess }];
  if (kind === 'propose') return [{ who: null, text: '誓いの指輪を差し出す。「これからの人生を、共に歩んでほしい」' }, { who: id, text: S.vow }];
  if (kind === 'home') return [{ who: id, text: S.home }];
  return [];
}

/* ── 場面の窓 ── */
export class SceneUI {
  constructor(game) { this.g = game; this.el = document.getElementById('scene'); }
  /** steps を順に見せる。返り値：選んだ答えが好みに合ったか（true/false/null） */
  play(steps) {
    return new Promise(done => {
      const el = this.el; if (!el) return done(null);
      let i = 0, hit = null;
      const nm = el.querySelector('.sc-name'), tx = el.querySelector('.sc-text'), pt = el.querySelector('.sc-face'), ch = el.querySelector('.sc-choices');
      const finish = () => { el.hidden = true; el.onclick = null; done(hit); };
      const next = () => {
        if (i >= steps.length) return finish();
        const s = steps[i++]; ch.innerHTML = '';
        if (s.choice) {
          nm.textContent = ''; tx.textContent = '';
          s.choice.forEach((t, k) => { const b = document.createElement('button'); b.className = 'gd-btn gold'; b.textContent = t;
            b.onclick = e => { e.stopPropagation(); hit = (k === s.good); ch.innerHTML = ''; steps.splice(i, 0, s.res[k]); next(); }; ch.appendChild(b); });
          return;
        }
        const c = s.who ? CHAR[s.who] : null;
        nm.textContent = c ? c.name : '';
        pt.style.background = c && c.tint ? '#' + (c.tint.hair >>> 0).toString(16).padStart(6, '0') : 'transparent';
        pt.textContent = c ? c.short : '';
        pt.style.visibility = c ? 'visible' : 'hidden';
        tx.textContent = s.text;
        tx.className = 'sc-text' + (c ? '' : ' nar');
        if (c && this.g.voice) try { this.g.voice.say(s.text.slice(0, 40), s.who); } catch (e) {}
      };
      el.hidden = false;
      el.onclick = () => { if (!ch.children.length) next(); };
      next();
    });
  }
}
